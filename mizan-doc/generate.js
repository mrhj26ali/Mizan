// ─── Helper: heading paragraph ────────────────────────────────────
function h1(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_1,
    bidirectional: true,
    children: [new TextRun({ text, font: "Arial", bold: true, size: 36, color: BLACK })]
  });
}
function h2(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_2,
    bidirectional: true,
    spacing: { before: 300, after: 120 },
    children: [new TextRun({ text, font: "Arial", bold: true, size: 28, color: BLACK })]
  });
}
function h3(text) {
  return new Paragraph({
    heading: HeadingLevel.HEADING_3,
    bidirectional: true,
    spacing: { before: 200, after: 80 },
    children: [new TextRun({ text, font: "Arial", bold: true, size: 24, color: BLACK })]
  });
}

// ─── Helper: normal body paragraph ────────────────────────────────
function body(text, { bold=false, italic=false, size=22, color=BLACK, spacing={before:60,after:80} } = {}) {
  return new Paragraph({
    bidirectional: true,
    alignment: AlignmentType.RIGHT,
    spacing,
    children: [new TextRun({ text, font: "Arial", bold, italic, size, color })]
  });
}

// Mixed runs paragraph (for inline code in Arabic text)
function bodyMixed(runs, spacing={before:60, after:80}) {
  return new Paragraph({
    bidirectional: true,
    alignment: AlignmentType.RIGHT,
    spacing,
    children: runs
  });
}

function ar(text, { bold=false, italic=false, size=22, color=BLACK } = {}) {
  return new TextRun({ text, font: "Arial", bold, italic, size, color });
}
function code(text) {
  return new TextRun({ text, font: "Courier New", bold: false, size: 20, color: "222222" });
}

// ─── Helper: code block ───────────────────────────────────────────
function codeBlock(lines) {
  return lines.map(line =>
    new Paragraph({
      alignment: AlignmentType.LEFT,
      bidirectional: false,
      spacing: { before: 0, after: 0 },
      shading: { fill: CODEBG, type: ShadingType.CLEAR },
      border: {
        top: { style: BorderStyle.NONE }, bottom: { style: BorderStyle.NONE },
        left: { style: BorderStyle.SINGLE, size: 8, color: "888888" }, right: { style: BorderStyle.NONE }
      },
      indent: { left: 200 },
      children: [new TextRun({ text: line, font: "Courier New", size: 19, color: "222222" })]
    })
  );
}

function codeBlockWrapper(lines) {
  const blockParagraphs = lines.map((line, i) => {
    const isFirst = i === 0;
    const isLast  = i === lines.length - 1;
    return new Paragraph({
      alignment: AlignmentType.LEFT,
      bidirectional: false,
      spacing: { before: 0, after: 0 },
      shading: { fill: CODEBG, type: ShadingType.CLEAR },
      indent: { left: 300, right: 300 },
      border: {
        top:    isFirst ? bdr("AAAAAA", 4) : noBorder,
        bottom: isLast  ? bdr("AAAAAA", 4) : noBorder,
        left:   bdr("AAAAAA", 4),
        right:  bdr("AAAAAA", 4),
      },
      children: [new TextRun({ text: line || " ", font: "Courier New", size: 19, color: "111111" })]
    });
  });
  return blockParagraphs;
}

// ─── Helper: divider line ─────────────────────────────────────────
function divider() {
  return new Paragraph({
    spacing: { before: 200, after: 200 },
    border: { bottom: { style: BorderStyle.SINGLE, size: 6, color: MGRAY } },
    children: []
  });
}

// ─── Helper: note / info box ──────────────────────────────────────
function noteBox(label, text) {
  return new Table({
    width: { size: 9360, type: WidthType.DXA },
    columnWidths: [9360],
    rows: [
      new TableRow({
        children: [
          new TableCell({
            borders: allBorders("888888", 4),
            shading: { fill: LGRAY, type: ShadingType.CLEAR },
            margins: { top: 100, bottom: 100, left: 160, right: 160 },
            children: [
              new Paragraph({
                bidirectional: true,
                alignment: AlignmentType.RIGHT,
                children: [
                  new TextRun({ text: label + " ", font: "Arial", bold: true, size: 21, color: BLACK }),
                  new TextRun({ text, font: "Arial", size: 21, color: BLACK }),
                ]
              })
            ]
          })
        ]
      })
    ]
  });
}

